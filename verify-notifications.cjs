const assert=require('assert/strict');
const fs=require('fs'),os=require('os'),path=require('path');
const {Store}=require('./store');const C=require('./src/schedule-core');const {NotificationEngine,dueEntries}=require('./notification-engine');
const temp=fs.mkdtempSync(path.join(os.tmpdir(),'desknote-notifications-'));
const store=new Store(temp);
const routine=(id,time,extra={})=>({id,title:id,time,endTime:'',days:[0,1,2,3,4,5,6],startDate:'',endDate:'',enabled:true,notify:true,notes:'',...extra});
const data={version:1,activeCat:'work',categories:[{id:'work',name:'Work',icon:''}],tasks:[],events:[],routines:[routine('breakfast','06:45'),routine('water','06:45'),routine('muted','06:45',{notify:false}),routine('exception','06:45',{excludeDates:['2026-11-09']})],routineChecks:[]};
store.write(data);
const at=value=>new Date('2026-11-09T'+value).getTime();
let clock=at('06:45:02'),messages=[];
const send=async payload=>messages.push(payload);
(async()=>{
  const engine=new NotificationEngine(store,{send,clock:()=>clock});
  await engine.tick();assert.equal(messages.length,1);assert.equal(messages[0].entries.length,2);
  await engine.tick();assert.equal(messages.length,1);
  clock+=10000;const restarted=new NotificationEngine(store,{send,clock:()=>clock});await restarted.tick();assert.equal(messages.length,1);
  restarted.configure({enabled:false});clock+=86400000;await restarted.tick();assert.equal(messages.length,1);
  assert.equal(new NotificationEngine(store,{send}).settings.enabled,false);
  restarted.configure({enabled:true,sound:false});await restarted.test();assert.equal(messages.at(-1).silent,true);
  const next={...structuredClone(data),events:[{id:'exam',title:'Exam',date:'2026-11-10',time:'00:05',endTime:'01:00',repeat:'none',important:true,notify:true,notes:''}]};
  const due=dueEntries(next,at('23:49:59'),at('23:50:03'));
  assert.equal(due.length,1);assert.equal(due[0].lead,15);assert.equal(due[0].item.date,'2026-11-10');
  const checks={...structuredClone(data),routineChecks:[{id:'breakfast:2026-11-09',routineId:'breakfast',date:'2026-11-09',done:true}]};
  assert(!dueEntries(checks,at('06:44:59'),at('06:45:03')).some(x=>x.item.sourceId==='breakfast'));
  const sessions={...structuredClone(data),routines:[routine('sleep','22:30',{endTime:'06:30'})],tasks:[{id:'work',title:'Work',plannedDate:'2026-11-09',plannedTime:'14:00',durationMinutes:30,done:false}]};
  assert.equal(C.currentSessions(sessions,at('14:10:00'))[0].sourceId,'work');
  assert.equal(C.currentSessions(sessions,at('14:30:00')).length,0);
  assert.equal(C.currentSessions(sessions,at('06:00:00'))[0].sourceId,'sleep');
  const advance=dueEntries(sessions,at('13:54:59'),at('13:55:03'));
  assert.equal(advance.length,1);assert.equal(advance[0].lead,5);assert.equal(advance[0].phase,'start');
  const start=dueEntries(sessions,at('13:59:59'),at('14:00:03'));
  assert.equal(start.length,1);assert.equal(start[0].lead,0);assert.notEqual(start[0].key,advance[0].key);
  assert.equal(dueEntries(sessions,at('13:54:59'),at('13:55:03'),{[advance[0].key]:{status:'shown'}}).length,0);
  assert.equal(dueEntries({...sessions,tasks:[{...sessions.tasks[0],done:true}]},at('13:54:59'),at('13:55:03')).length,0);
  assert.equal(dueEntries({...sessions,tasks:[{...sessions.tasks[0],notify:false}]},at('13:54:59'),at('13:55:03')).length,0);
  const midnightTask={...sessions,routines:[],tasks:[{...sessions.tasks[0],plannedDate:'2026-11-10',plannedTime:'00:03'}]};
  assert.equal(dueEntries(midnightTask,at('23:57:59'),at('23:58:03'))[0].lead,5);
  const ends=dueEntries(sessions,at('06:29:59'),at('06:30:03'));
  assert.equal(ends.length,1);assert.equal(ends[0].phase,'end');assert.equal(ends[0].item.date,'2026-11-08');
  assert.equal(dueEntries(sessions,at('14:29:59'),at('14:30:03'))[0].phase,'end');
  assert.equal(dueEntries(sessions,at('14:29:59'),at('14:30:03'),{[dueEntries(sessions,at('14:29:59'),at('14:30:03'))[0].key]:{status:'shown'}}).length,0);
  const failureDir=fs.mkdtempSync(path.join(os.tmpdir(),'desknote-reminder-fail-'));const failStore=new Store(failureDir);failStore.write(data);
  clock=at('06:45:02');let attempts=0;
  const failure=new NotificationEngine(failStore,{clock:()=>clock,send:async()=>{attempts++;throw Error('simulated toast failure');}});
  await failure.tick();assert.equal(attempts,1);assert.equal(failure.state.lastShownAt,null);assert(failure.status().lastError);
  clock+=10000;await failure.tick();assert.equal(attempts,1);
  clock+=30000;await failure.tick();assert.equal(attempts,2);
  clock+=30000;await failure.tick();assert.equal(attempts,2);
  const oldDir=fs.mkdtempSync(path.join(os.tmpdir(),'desknote-resume-'));const oldStore=new Store(oldDir);oldStore.write(data);
  const resumed=new NotificationEngine(oldStore,{clock:()=>at('12:00:00'),send});resumed.lastTick=at('06:00:00');
  const count=messages.length;await resumed.tick();assert.equal(messages.length,count,'Do not replay hours of missed reminders after sleep.');
  assert.throws(()=>store.command({command:'routine.update',id:'water',fields:{notify:'yes'}}));
  console.log('PASS: due-time scheduling, same-time grouping, persisted deduplication, day exceptions, opt-out, completion, cross-midnight advance reminders, settings, failures/retry, sleep resume.');
})().catch(error=>{console.error(error);process.exitCode=1;});
