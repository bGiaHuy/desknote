const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('nest', {
  load: () => ipcRenderer.invoke('data:load'),
  save: (data) => ipcRenderer.send('data:save', data),
  saveSync: (data) => ipcRenderer.sendSync('data:save-sync', data),
  command: (request) => ipcRenderer.invoke('data:command', request),

  expandSide: () => ipcRenderer.invoke('win:expand-side'),
  setExpanded: (on) => ipcRenderer.invoke('win:set-expanded', on),
  setMini: (on) => ipcRenderer.invoke('win:set-mini', on),
  hide: () => ipcRenderer.send('win:hide'),
  togglePin: () => ipcRenderer.invoke('win:toggle-pin'),
  getPin: () => ipcRenderer.invoke('win:get-pin'),
  onPinChanged: (fn) => ipcRenderer.on('pinned-changed', (_e, v) => fn(v)),

  getAutoStart: () => ipcRenderer.invoke('app:get-autostart'),
  setAutoStart: (on) => ipcRenderer.invoke('app:set-autostart', on),
  quit: () => ipcRenderer.send('app:quit'),
  openData: () => ipcRenderer.send('app:open-data'),
  onExternalChange: (fn) => ipcRenderer.on('data:external-change', () => fn()),
  onRestore: (fn) => ipcRenderer.on('win:restore', () => fn()),
  agyStatus: () => ipcRenderer.invoke('agy:status'),
  agyHistory: () => ipcRenderer.invoke('agy:history'),
  agySend: (text) => ipcRenderer.invoke('agy:send', text),
  agyCancel: () => ipcRenderer.send('agy:cancel'),
  agyOpenApp: () => ipcRenderer.invoke('agy:open-app'),
  getNotifications: () => ipcRenderer.invoke('notifications:status'),
  configureNotifications: (fields) => ipcRenderer.invoke('notifications:configure', fields),
  testNotification: () => ipcRenderer.invoke('notifications:test'),
  onNotificationOpen: (fn) => ipcRenderer.on('notification:open', (_event,item) => fn(item)),
  getReviews: () => ipcRenderer.invoke('reviews:status'),
  configureReviews: (fields) => ipcRenderer.invoke('reviews:configure',fields),
  undoReviewRoutines: () => ipcRenderer.invoke('reviews:undo'),
  runReview: () => ipcRenderer.invoke('reviews:run'),
  onReviewUpdated: (fn) => ipcRenderer.on('review:updated',()=>fn()),
});
